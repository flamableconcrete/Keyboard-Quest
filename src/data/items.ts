export function getItemColor(rarity?: string): string {
  switch (rarity) {
    case 'uncommon':
      return '#1eff00'
    case 'rare':
      return '#0070dd'
    case 'epic':
      return '#a335ee'
    case 'common':
    default:
      return '#ffffff'
  }
}
